-- 6. Проверка записи в fee_payments: пробная строка на существующего админа и сразу откат (в базе ничего не остаётся)
CREATE TEMP TABLE IF NOT EXISTS iva_yk_check (ok boolean, err text) ON COMMIT PRESERVE ROWS;
TRUNCATE iva_yk_check;
DO $do$
DECLARE
  e text;
BEGIN
  SELECT lower(btrim(x.email)) INTO e FROM public.admins x WHERE coalesce(x.role, '') <> 'chief' AND coalesce(x.email, '') <> '' LIMIT 1;
  IF e IS NULL THEN
    INSERT INTO iva_yk_check VALUES (true, 'нет админов — проверять не на ком');
    RETURN;
  END IF;
  BEGIN
    PERFORM public.iva_yk_fee_insert(e, 1, 'ЮKassa · пробная запись SQL 1123 (откатывается)');
    RAISE EXCEPTION 'IVA_ROLLBACK_OK';
  EXCEPTION WHEN others THEN
    IF sqlerrm = 'IVA_ROLLBACK_OK' THEN INSERT INTO iva_yk_check VALUES (true, NULL);
    ELSE INSERT INTO iva_yk_check VALUES (false, left(sqlerrm, 200)); END IF;
  END;
END $do$;

-- 7. Проверка: все строки должны быть «✅»
SELECT x.check_name, CASE WHEN x.ok THEN '✅' ELSE '❌' END AS result FROM (VALUES
  ('онлайн-оплаты: админ видит свои, владелец площадки — все, писать напрямую нельзя',
     to_regclass('public.iva_yk_pay') IS NOT NULL
     AND (SELECT relrowsecurity FROM pg_class WHERE oid = 'public.iva_yk_pay'::regclass)
     AND EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'iva_yk_pay' AND policyname = 'iva_yk_pay_read')
     AND has_table_privilege('authenticated', 'public.iva_yk_pay', 'SELECT')
     AND NOT has_table_privilege('authenticated', 'public.iva_yk_pay', 'INSERT')
     AND NOT has_table_privilege('authenticated', 'public.iva_yk_pay', 'UPDATE')
     AND NOT has_table_privilege('anon', 'public.iva_yk_pay', 'SELECT')),
  ('служебные функции — только для сервера',
     has_function_privilege('service_role', 'public.iva_yk_done(text, text, numeric, boolean, text, text)', 'EXECUTE')
     AND NOT has_function_privilege('authenticated', 'public.iva_yk_done(text, text, numeric, boolean, text, text)', 'EXECUTE')
     AND NOT has_function_privilege('authenticated', 'public.iva_yk_new(text, numeric)', 'EXECUTE')
     AND NOT has_function_privilege('authenticated', 'public.iva_yk_fee_insert(text, numeric, text)', 'EXECUTE')
     AND NOT has_function_privilege('anon', 'public.iva_yk_set(bigint, text, text)', 'EXECUTE')
     AND NOT has_function_privilege('anon', 'public.iva_yk_open(text, bigint)', 'EXECUTE')),
  ('«Чек пробит» — вызов только для вошедших (внутри — только владелец площадки)',
     has_function_privilege('authenticated', 'public.iva_yk_receipt(bigint, boolean)', 'EXECUTE')
     AND NOT has_function_privilege('anon', 'public.iva_yk_receipt(bigint, boolean)', 'EXECUTE')),
  ('оплата записывается в fee_payments как подтверждённая (проба с откатом)' ||
     coalesce(': ' || (SELECT err FROM iva_yk_check WHERE NOT ok LIMIT 1), ''),
     coalesce((SELECT bool_and(ok) FROM iva_yk_check), false))
) AS x(check_name, ok);
