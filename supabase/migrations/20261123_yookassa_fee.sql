-- ============================================================
--  Ива 10.133 — оплата комиссии площадки онлайн через ЮKassa владельца площадки (просьба владельца 04.11.2026:
--  «подключить платежи владельцев прокатов к моей юкассе»). Решения владельца: платят только комиссию; кнопка —
--  только в приложении; сумма любая (по умолчанию — весь долг); чеки самозанятого владелец пробивает сам в «Мой налог»
--  (ЮKassa с 29.12.2025 чеки самозанятых не отправляет) — нужен список онлайн-оплат с отметкой «Чек пробит».
--
--  Что делает:
--   • iva_yk_pay — онлайн-оплаты: кто (почта админа), сумма, статус ЮKassa, номер платежа ЮKassa, способ оплаты
--     (sbp / bank_card …), когда оплачено, отметка «Чек пробит». Ни карт, ни телефонов, ни имён.
--     Читает админ — свои, владелец площадки — все. Писать напрямую не может никто: только сервер (функция iva-pay)
--     через служебные функции ниже и владелец площадки — отметку «Чек пробит» (iva_yk_receipt).
--   • Деньги в долг засчитываются ТОЛЬКО после того, как сервер сам спросил ЮKassa и получил «succeeded / paid»:
--     тогда iva_yk_done пишет в fee_payments обычную строку «confirmed» (как подтверждённая вручную) — сайт,
--     приложение и «Панель владельца» считают долг как раньше. Строки «pending» в fee_payments онлайн-оплаты
--     не создают (их на сайте можно было бы «Подтвердить» без денег).
--   • Повторное уведомление ЮKassa ничего не удваивает: платёж засчитывается один раз (блокировка строки).
--
--  Без этого SQL кнопка «Оплатить онлайн» в приложении скажет «Онлайн-оплата пока не подключена».
--
--  КАК ЗАПУСТИТЬ: Supabase → SQL Editor → New query → вставить ВЕСЬ файл → Run. Можно запускать повторно.
--  В конце — проверка: все строки должны быть «✅» (последняя пробует записать оплату в fee_payments и сразу
--  откатывает — в базе ничего не остаётся).
--  ОТКАТ: supabase/migrations/20261123_yookassa_fee_rollback.sql (fee_payments не меняется).
-- ============================================================

DO $do$
BEGIN
  IF to_regclass('public.admins') IS NULL OR to_regclass('public.fee_payments') IS NULL
     OR to_regprocedure('public.fn_is_chief()') IS NULL OR to_regprocedure('public.jwt_email()') IS NULL THEN
    RAISE EXCEPTION 'В базе нет admins / fee_payments / fn_is_chief / jwt_email — это не база «Ивы»';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    RAISE EXCEPTION 'Нет роли service_role — это не Supabase';
  END IF;
END $do$;

-- 1. Онлайн-оплаты
CREATE TABLE IF NOT EXISTS public.iva_yk_pay (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_email      text        NOT NULL CHECK (admin_email = lower(btrim(admin_email)) AND admin_email <> ''),
  amount           numeric(12,2) NOT NULL CHECK (amount >= 1 AND amount <= 100000),
  status           text        NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'pending', 'succeeded', 'canceled')),
  yk_id            text        UNIQUE,
  confirmation_url text,
  method           text,
  cancel_reason    text,
  fee_payment_id   text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  paid_at          timestamptz,
  receipt_done     boolean     NOT NULL DEFAULT false,
  receipt_at       timestamptz,
  receipt_by       text
);
CREATE INDEX IF NOT EXISTS iva_yk_pay_admin ON public.iva_yk_pay (admin_email, id DESC);
COMMENT ON TABLE public.iva_yk_pay IS 'Ива 10.133: оплата комиссии через ЮKassa. Пишет только сервер (iva-pay); админ видит свои, владелец площадки — все и отмечает «Чек пробит»';
ALTER TABLE public.iva_yk_pay ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.iva_yk_pay FROM public, anon, authenticated;
GRANT SELECT ON public.iva_yk_pay TO authenticated;
GRANT ALL ON public.iva_yk_pay TO service_role;
DROP POLICY IF EXISTS iva_yk_pay_read ON public.iva_yk_pay;
CREATE POLICY iva_yk_pay_read ON public.iva_yk_pay FOR SELECT TO authenticated
  USING (admin_email = public.jwt_email() OR public.fn_is_chief());

-- 2. Запись подтверждённой оплаты в fee_payments (как подтверждённая вручную). Столбцы note / confirmed_at /
--    confirmed_by — если есть; не вышло с ними — без них. Не вышло совсем — ошибка (платёж останется «pending»,
--    ЮKassa повторит уведомление, приложение — проверку).
CREATE OR REPLACE FUNCTION public.iva_yk_fee_insert(p_email text, p_amount numeric, p_note text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  cols text := 'admin_email, amount, status';
  vals text := '$1, $2, ''confirmed''';
  fid  text;
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'fee_payments' and column_name = 'note') then
    cols := cols || ', note'; vals := vals || ', $3';
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'fee_payments' and column_name = 'confirmed_at') then
    cols := cols || ', confirmed_at'; vals := vals || ', now()';
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'fee_payments' and column_name = 'confirmed_by') then
    cols := cols || ', confirmed_by'; vals := vals || ', ''ЮKassa''';
  end if;
  begin
    execute format('insert into public.fee_payments (%s) values (%s) returning id::text', cols, vals)
      into fid using lower(btrim(p_email)), p_amount, p_note;
  exception when others then
    raise notice 'iva_yk_fee_insert: с доп. столбцами не вышло (%), пишу без них', sqlerrm;
    execute 'insert into public.fee_payments (admin_email, amount, status) values ($1, $2, ''confirmed'') returning id::text'
      into fid using lower(btrim(p_email)), p_amount;
  end;
  return fid;
end
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_fee_insert(text, numeric, text) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_fee_insert(text, numeric, text) TO service_role;

-- 3. Новая оплата (сервер, после проверки ключа входа): только админ проката (не владелец площадки),
--    1–100 000 ₽, не больше 5 незавершённых за 10 минут.
CREATE OR REPLACE FUNCTION public.iva_yk_new(p_email text, p_amount numeric)
 RETURNS bigint
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  e  text := lower(btrim(coalesce(p_email, '')));
  a  numeric := round(coalesce(p_amount, 0), 2);
  nid bigint;
begin
  if e = '' or not exists (select 1 from public.admins x where lower(btrim(x.email)) = e and coalesce(x.role, '') <> 'chief') then
    raise exception 'IVA_NOT_ADMIN';
  end if;
  if a < 1 or a > 100000 then raise exception 'IVA_BAD_AMOUNT'; end if;
  if (select count(*) from public.iva_yk_pay p where p.admin_email = e and p.status in ('new', 'pending')
        and p.created_at > now() - interval '10 minutes') >= 5 then
    raise exception 'IVA_TOO_MANY';
  end if;
  insert into public.iva_yk_pay (admin_email, amount) values (e, a) returning iva_yk_pay.id into nid;
  return nid;
end
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_new(text, numeric) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_new(text, numeric) TO service_role;

-- ЮKassa создала платёж — номер и ссылка оплаты
CREATE OR REPLACE FUNCTION public.iva_yk_set(p_id bigint, p_yk_id text, p_url text)
 RETURNS void
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  update public.iva_yk_pay set yk_id = nullif(btrim(p_yk_id), ''), confirmation_url = p_url, status = 'pending'
   where id = p_id and status = 'new';
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_set(bigint, text, text) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_set(bigint, text, text) TO service_role;

-- ЮKassa отказала в создании платежа
CREATE OR REPLACE FUNCTION public.iva_yk_fail(p_id bigint, p_reason text)
 RETURNS void
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  update public.iva_yk_pay set status = 'canceled', cancel_reason = left(coalesce(p_reason, ''), 200)
   where id = p_id and status = 'new';
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_fail(bigint, text) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_fail(bigint, text) TO service_role;

-- Незавершённые оплаты админа за 3 дня (сервер спросит у ЮKassa их статус)
CREATE OR REPLACE FUNCTION public.iva_yk_open(p_email text, p_id bigint DEFAULT NULL)
 RETURNS TABLE (id bigint, yk_id text)
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select p.id, p.yk_id from public.iva_yk_pay p
   where p.admin_email = lower(btrim(coalesce(p_email, ''))) and p.status = 'pending' and p.yk_id is not null
     and (p_id is null or p.id = p_id) and p.created_at > now() - interval '3 days'
   order by p.id desc limit 5;
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_open(text, bigint) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_open(text, bigint) TO service_role;

-- 4. Итог платежа — ТОЛЬКО то, что сервер сам получил от ЮKassa (GET /v3/payments/{id}).
--    succeeded + paid + сумма совпала → строка «confirmed» в fee_payments (один раз); canceled → отмена.
CREATE OR REPLACE FUNCTION public.iva_yk_done(p_yk_id text, p_status text, p_amount numeric, p_paid boolean, p_method text, p_reason text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  r   public.iva_yk_pay%rowtype;
  fid text;
begin
  select * into r from public.iva_yk_pay where yk_id = nullif(btrim(coalesce(p_yk_id, '')), '') for update;
  if not found then return null; end if;                                    -- не наш платёж
  if r.status in ('pending', 'new') then
    if p_status = 'succeeded' and coalesce(p_paid, false) then
      if round(coalesce(p_amount, -1), 2) <> r.amount then
        raise exception 'IVA_AMOUNT_MISMATCH: платёж % — ждали %, ЮKassa: %', r.id, r.amount, p_amount;
      end if;
      fid := public.iva_yk_fee_insert(r.admin_email, r.amount, 'ЮKassa · онлайн-оплата №' || r.id || ' · ' || r.yk_id);
      update public.iva_yk_pay set status = 'succeeded', paid_at = now(), method = left(coalesce(p_method, ''), 40), fee_payment_id = fid
       where id = r.id returning * into r;
    elsif p_status = 'canceled' then
      update public.iva_yk_pay set status = 'canceled', cancel_reason = left(coalesce(p_reason, ''), 200)
       where id = r.id returning * into r;
    end if;
  end if;
  return jsonb_build_object('id', r.id, 'status', r.status, 'amount', r.amount);
end
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_done(text, text, numeric, boolean, text, text) FROM public, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.iva_yk_done(text, text, numeric, boolean, text, text) TO service_role;

-- 5. «Чек пробит» — только владелец площадки, только у оплаченных
CREATE OR REPLACE FUNCTION public.iva_yk_receipt(p_id bigint, p_done boolean)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.fn_is_chief() then raise exception 'Отмечать чеки может только владелец площадки'; end if;
  update public.iva_yk_pay
     set receipt_done = coalesce(p_done, false),
         receipt_at = case when coalesce(p_done, false) then now() end,
         receipt_by = case when coalesce(p_done, false) then public.jwt_email() end
   where id = p_id and status = 'succeeded';
  return found;
end
$function$;
REVOKE ALL ON FUNCTION public.iva_yk_receipt(bigint, boolean) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.iva_yk_receipt(bigint, boolean) TO authenticated;

