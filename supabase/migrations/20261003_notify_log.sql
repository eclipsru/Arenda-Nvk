-- ============================================================
--  Ива — журнал уведомлений (этап П5, шаг 1).
--
--  Зачем: чтобы одно и то же уведомление о заявке не пришло дважды.
--  Перед отправкой функция notify-order делает пометку в этой таблице;
--  если пометка уже стоит — значит, заявка уведомлена, второй раз не шлём.
--  Если отправка не удалась, функция снимает пометку (следующая попытка
--  сможет отправить снова).
--
--  Таблица служебная: правила доступа включены, политик нет — то есть
--  ни посетитель сайта, ни вошедший пользователь её не увидят.
--  Читает и пишет только сервисный ключ (он живёт в секретах функции).
--
--  Никаких персональных данных здесь нет: только номер заявки и время.
--
--  КАК ПРИМЕНИТЬ (действие владельца): SQL-редактор Supabase →
--  вставить текст → Run. Уже применяли так же П2 и срок хранения П4.
--
--  КАК ОТКАТИТЬ:
--    DROP TABLE IF EXISTS public.notify_log;
--  (сама рассылка уведомлений от этого не ломается: функция увидит, что
--   таблицы нет, и просто будет шлать без защиты от повторов)
-- ============================================================

CREATE TABLE IF NOT EXISTS public.notify_log (
  order_id bigint PRIMARY KEY,
  sent_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.notify_log ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.notify_log IS
  'Служебный журнал: какие заявки уже отправлены уведомлением в Telegram (этап П5). Персональных данных не содержит.';
