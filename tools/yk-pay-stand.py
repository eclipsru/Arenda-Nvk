# Стенд 10.133 «Оплата комиссии через ЮKassa»: 20261123_yookassa_fee.sql на настоящем PostgreSQL (pgserver).
#
# База: BASELINE (admins, fn_is_chief, jwt_email) + роль service_role + fee_payments как на сайте (id, admin_email,
# amount, status pending/confirmed, note, created_at, confirmed_at, confirmed_by) с RLS. Проверяет: файл применяется
# и повторяется, все «✅»; новая оплата — только админу (не владельцу площадки, не чужому), сумма 1–100 000, не больше
# 5 незавершённых за 10 минут; служебные функции не вызвать ни гостю, ни вошедшему; писать в таблицу напрямую нельзя;
# админ видит свои оплаты, другой админ — нет, владелец площадки — все; итог «succeeded + paid» → одна строка
# «confirmed» в fee_payments (повтор уведомления — не удваивает); не оплачено / чужой номер / другая сумма — не пишет;
# отмена; «Чек пробит» — только владелец площадки и только у оплаченных; fee_payments без confirmed_by и с триггером,
# который мешает доп. столбцам, — всё равно пишет; откат не трогает fee_payments.
#
# Запуск: python tools/yk-pay-stand.py  (нужен pip-пакет pgserver)
import ast
