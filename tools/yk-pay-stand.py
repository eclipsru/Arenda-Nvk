# ── откат ──
st, out = q(srv, RB)
check('откат: таблица и функции убраны, fee_payments на месте', st == 'OK' and '✅' in out
      and val(srv, "select to_regclass('public.iva_yk_pay') is null and to_regprocedure('public.iva_yk_done(text, text, numeric, boolean, text, text)') is null") == 't'
      and val(srv, 'select count(*) from public.fee_payments') == '1', out[-400:])
st, out = q(srv, SQL)
check('после отката применяется снова', st == 'OK' and out.count('✅') == 4, out[-400:])
srv.cleanup()

# ── fee_payments без confirmed_by / note и с триггером против доп. столбцов ──
srv2 = mk()
FEE2 = FEE.replace(', confirmed_by text', '').replace('  note text, ', '  ')
st, out = q(srv2, BASELINE + FEE2 + """
create function public.no_confirmed_at() returns trigger language plpgsql as $$
begin
  if new.confirmed_at is not null and coalesce(current_setting('iva.block', true), '') = '1' then raise exception 'confirmed_at запрещён'; end if;
  return new; end $$;
create trigger trg_no_confirmed_at before insert on public.fee_payments for each row execute function public.no_confirmed_at();
""")
