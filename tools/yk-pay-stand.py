import pgserver
import pgserver.postgres_server

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rd(p):
    return open(os.path.join(ROOT, p), encoding='utf-8').read()


def const(path, name):
    for node in ast.parse(rd(path)).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], 'id', '') == name:
            return ast.literal_eval(node.value)
    raise SystemExit('нет %s в %s' % (name, path))


SQL = rd('supabase/migrations/20261123_yookassa_fee.sql')
RB = rd('supabase/migrations/20261123_yookassa_fee_rollback.sql')
BASELINE = const('tools/category-tree-stand.py', 'BASELINE')
FEE = """
create role service_role nologin;
grant usage on schema public to service_role;
grant usage on schema auth to service_role;
grant execute on function auth.jwt() to service_role;
insert into public.admins values ('admin2@x.ru', 'admin', true), ('paused@x.ru', 'admin', false);
create table public.fee_payments(id bigint generated by default as identity primary key, admin_email text not null,
  amount numeric not null, status text not null default 'pending' check (status in ('pending', 'confirmed', 'rejected')),
  note text, created_at timestamptz default now(), confirmed_at timestamptz, confirmed_by text);
alter table public.fee_payments enable row level security;
create policy fee_own on public.fee_payments for select using (admin_email = public.jwt_email() or public.fn_is_chief());
"""

PSQL = str(pgserver.postgres_server.POSTGRES_BIN_PATH / 'psql')
fails = 0


def check(name, cond, detail=''):
    global fails
    if cond:
        print('✔ ' + name)
    else:
        fails += 1
        print('✘ ' + name + (' — ' + str(detail)[:900] if detail else ''))


def mk():
    return pgserver.get_server(tempfile.mkdtemp(), cleanup_mode='stop')


def q(srv, sql):
    r = subprocess.run('%s %s' % (PSQL, srv.get_uri()), input=('\\set ON_ERROR_STOP on\n' + sql + "\n;\nselect 'IVA-END-OK' as mark;\n").encode(),
                       shell=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    out = r.stdout.decode('utf-8', 'replace').strip()
    return ('OK' if 'IVA-END-OK' in out else 'ERR'), out.replace('IVA-END-OK', '')


def val(srv, sql):
    st, out = q(srv, '\\pset tuples_only on\n\\pset format unaligned\n' + sql)
    lines = [l for l in out.splitlines() if l and not l.startswith(('Tuples only', 'Output format', 'mark'))]
    return ';'.join(x for x in lines if x not in ('BEGIN', 'SET', 'COMMIT', 'INSERT 0 1', 'UPDATE 1', 'DELETE 1', 'UPDATE 0', 'DELETE 0'))


def claims(email):
    c = {'role': 'authenticated'}
    if email:
        c['email'] = email
        c['sub'] = str(uuid.uuid5(uuid.NAMESPACE_DNS, email))
    return json.dumps(c).replace("'", "''")


def as_(srv, email, sql, role='authenticated'):
    st, out = q(srv, "begin; set local role %s; set local request.jwt.claims = '%s'; %s; commit;" % (role, claims(email), sql))
    if out.rstrip().endswith('ROLLBACK') or 'ERROR' in out:
        st = 'ERR'
    return st, out


def as_val(srv, email, sql, role='authenticated'):
    return val(srv, "begin; set local role %s; set local request.jwt.claims = '%s'; %s; commit;" % (role, claims(email), sql))


def svc(srv, sql):
    return as_(srv, None, sql, 'service_role')


def svc_val(srv, sql):
    return as_val(srv, None, sql, 'service_role')


A, A2, CH = 'admin@x.ru', 'admin2@x.ru', 'chief@x.ru'

srv = mk()
st, out = q(srv, BASELINE + FEE)
check('исходная база (admins, fn_is_chief, fee_payments как на сайте, service_role)', st == 'OK', out[-600:])
st, out = q(srv, SQL)
check('20261123 применяется', st == 'OK', out[-900:])
check('проверка в конце: 4 «✅», ни одного «❌»', out.count('✅') == 4 and '❌' not in out, out[-900:])
check('пробная запись откатилась — fee_payments пуст', val(srv, 'select count(*) from public.fee_payments') == '0')
st, out = q(srv, SQL)
check('20261123 повторно — без ошибок', st == 'OK' and out.count('✅') == 4, out[-600:])

# ── новая оплата ──
I1 = svc_val(srv, "select public.iva_yk_new('Admin@X.ru ', 1500.555)")
check('сервер: новая оплата админа (почта приводится, сумма до копеек)', I1.isdigit()
      and val(srv, 'select admin_email || \'|\' || amount || \'|\' || status from public.iva_yk_pay where id = %s' % I1) == 'admin@x.ru|1500.56|new')
check('владельцу площадки оплату не создать', 'IVA_NOT_ADMIN' in svc(srv, "select public.iva_yk_new('%s', 100)" % CH)[1])
check('чужой почте (не админ) — нельзя', 'IVA_NOT_ADMIN' in svc(srv, "select public.iva_yk_new('client@x.ru', 100)")[1])
check('приостановленный админ может оплатить долг', svc_val(srv, "select public.iva_yk_new('paused@x.ru', 10)").isdigit())
check('сумма меньше 1 ₽ — нельзя', 'IVA_BAD_AMOUNT' in svc(srv, "select public.iva_yk_new('%s', 0.5)" % A)[1])
check('сумма больше 100 000 ₽ — нельзя', 'IVA_BAD_AMOUNT' in svc(srv, "select public.iva_yk_new('%s', 100000.01)" % A)[1])
for i in range(4):
    svc_val(srv, "select public.iva_yk_new('%s', 10)" % A2)
check('5 незавершённых за 10 минут — можно', svc_val(srv, "select public.iva_yk_new('%s', 10)" % A2).isdigit())
check('6-я подряд — «слишком часто»', 'IVA_TOO_MANY' in svc(srv, "select public.iva_yk_new('%s', 10)" % A2)[1])

# ── права ──
st, out = as_(srv, A, "select public.iva_yk_new('%s', 100)" % A)
check('вошедший сам вызвать iva_yk_new не может', st == 'ERR' and 'permission denied' in out, out[-300:])
st, out = as_(srv, A, "select public.iva_yk_done('x', 'succeeded', 1, true, 'sbp', null)")
check('вошедший не может сам «оплатить» (iva_yk_done)', st == 'ERR' and 'permission denied' in out, out[-300:])
st, out = as_(srv, A, "select public.iva_yk_fee_insert('%s', 100, 'x')" % A)
check('вошедший не может писать оплату в fee_payments через функцию', st == 'ERR' and 'permission denied' in out, out[-300:])
st, out = as_(srv, None, "select public.iva_yk_open('%s', null)" % A, 'anon')
check('гость не видит незавершённые оплаты', st == 'ERR' and 'permission denied' in out, out[-300:])
st, out = as_(srv, A, "insert into public.iva_yk_pay(admin_email, amount) values ('%s', 5)" % A)
check('писать в таблицу напрямую нельзя', st == 'ERR', out[-300:])
st, out = as_(srv, A, "update public.iva_yk_pay set status = 'succeeded' where id = %s" % I1)
check('менять статус напрямую нельзя', st == 'ERR' and val(srv, 'select status from public.iva_yk_pay where id = %s' % I1) == 'new', out[-300:])

# ── платёж создан в ЮKassa ──
svc(srv, "select public.iva_yk_set(%s, 'yk-111', 'https://yoomoney.ru/checkout/payments/v2/contract?orderId=yk-111')" % I1)
check('номер ЮKassa и ссылка записаны, статус «pending»', val(srv, "select status || '|' || yk_id from public.iva_yk_pay where id = %s" % I1) == 'pending|yk-111')
check('незавершённые оплаты админа для проверки', svc_val(srv, "select id || ':' || yk_id from public.iva_yk_open('%s', null)" % A) == I1 + ':yk-111')
check('по номеру — только своя', svc_val(srv, "select count(*) from public.iva_yk_open('%s', %s)" % (A2, I1)) == '0')
check('админ видит свою оплату', as_val(srv, A, 'select count(*) from public.iva_yk_pay where id = %s' % I1).endswith('1'))
check('другой админ чужую не видит', as_val(srv, A2, 'select count(*) from public.iva_yk_pay where id = %s' % I1).endswith('0'))
check('владелец площадки видит все', as_val(srv, CH, 'select count(*) > 5 from public.iva_yk_pay').endswith('t'))
check('гость не видит', as_(srv, None, 'select count(*) from public.iva_yk_pay', 'anon')[0] == 'ERR')

# ── итог ──
r = svc_val(srv, "select public.iva_yk_done('yk-111', 'pending', 1500.56, false, null, null)")
check('«ещё не оплачено» — ничего не пишет', '"pending"' in r and val(srv, 'select count(*) from public.fee_payments') == '0', r)
r = svc_val(srv, "select public.iva_yk_done('yk-111', 'succeeded', 1500.56, false, 'sbp', null)")
check('succeeded без paid — не засчитывается', val(srv, 'select count(*) from public.fee_payments') == '0', r)
check('чужой номер ЮKassa — пусто, ничего не пишет', svc_val(srv, "select coalesce(public.iva_yk_done('yk-999', 'succeeded', 5, true, 'sbp', null)::text, 'null')") == 'null')
st, out = svc(srv, "select public.iva_yk_done('yk-111', 'succeeded', 1500, true, 'sbp', null)")
check('другая сумма — ошибка, не засчитано', st == 'ERR' and 'IVA_AMOUNT_MISMATCH' in out and val(srv, 'select count(*) from public.fee_payments') == '0', out[-300:])
r = svc_val(srv, "select public.iva_yk_done('yk-111', 'succeeded', 1500.56, true, 'sbp', null)")
check('оплачено → succeeded', '"succeeded"' in r, r)
row = val(srv, "select admin_email || '|' || amount || '|' || status || '|' || (confirmed_at is not null) || '|' || confirmed_by || '|' || note from public.fee_payments")
check('в fee_payments одна подтверждённая строка (почта, сумма, когда, кем, номер)',
      row.startswith('admin@x.ru|1500.56|confirmed|true|ЮKassa|ЮKassa · онлайн-оплата №%s · yk-111' % I1), row)
check('связь оплаты со строкой fee_payments и способ оплаты',
      val(srv, "select (fee_payment_id = (select id::text from public.fee_payments)) || '|' || method || '|' || (paid_at is not null) from public.iva_yk_pay where id = %s" % I1) == 'true|sbp|true')
svc(srv, "select public.iva_yk_done('yk-111', 'succeeded', 1500.56, true, 'sbp', null)")
svc(srv, "select public.iva_yk_done('yk-111', 'canceled', 1500.56, false, null, 'expired_on_confirmation')")
check('повтор уведомления и поздняя «отмена» — не удваивает и не отменяет', val(srv, 'select count(*) from public.fee_payments') == '1'
      and val(srv, 'select status from public.iva_yk_pay where id = %s' % I1) == 'succeeded')
check('админ видит оплату в fee_payments (как подтверждённую вручную)', as_val(srv, A, "select count(*) from public.fee_payments where status = 'confirmed'").endswith('1'))
check('больше не в списке незавершённых', svc_val(srv, "select count(*) from public.iva_yk_open('%s', null)" % A) == '0')

I2 = svc_val(srv, "select public.iva_yk_new('%s', 300)" % A)
svc(srv, "select public.iva_yk_set(%s, 'yk-222', 'u')" % I2)
r = svc_val(srv, "select public.iva_yk_done('yk-222', 'canceled', 300, false, null, 'expired_on_confirmation')")
