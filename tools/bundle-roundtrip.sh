#!/usr/bin/env bash
# Круговой тест канала «пакет одним файлом»: упаковали → разложили → сверили.
#
# Проверяет то, что легко сломать незаметно:
#   • файлы с русскими именами и вложенные папки доезжают;
#   • примеры из инструкций (`postgres://postgres:<пароль>@…`, `[YOUR-PASSWORD]`) НЕ считаются
#     секретом — иначе полезные документы молча выпадают из передачи;
#   • настоящий секрет (похожий на токен бота) НЕ уезжает: упаковщик его пропускает;
#   • файл со строкой-маркером «КОНЕЦ ФАЙЛА» внутри пропускается (он сломал бы разбор);
#   • после раскладки содержимое совпадает побайтно.
#
# Запуск: bash tools/bundle-roundtrip.sh   (код 0 — всё хорошо, 1 — поломка)
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
SRC="$TMP/пакет"
OUT="$TMP/связка.md"
DST="$TMP/разложено"
mkdir -p "$SRC/вложенная папка"

printf 'Привет, мир\nСтрока два\n' > "$SRC/00-обычный.md"
printf 'pg_dump "postgresql://postgres:<пароль>@db.x.supabase.co:5432/postgres"\n' > "$SRC/инструкция-образец.md"
printf 'postgresql://postgres.abc:[YOUR-PASSWORD]@aws-0-eu-central-1.pooler.supabase.com:5432/postgres\n' > "$SRC/вложенная папка/ещё-образец.md"
printf 'токен: %s:%s\n' "8123456789" "AAFfakeFAKEFakeTokenFakeTokenFakeTo" > "$SRC/утечка.md"
printf 'текст\n===== %s =====\nещё текст\n' "КОНЕЦ ФАЙЛА" > "$SRC/ломкий.md"

fail=0
say() { printf '  %s %s\n' "$1" "$2"; }

python3 "$ROOT/tools/pack_bundle.py" "$SRC" "$OUT" --prefix пакет > "$TMP/pack.log" 2>&1
grep -q "утечка.md" "$TMP/pack.log" && say "✔" "настоящий секрет не упакован (утечка.md пропущена)" || { say "✘" "секрет уехал в пакет!"; fail=1; }
grep -q "ломкий.md" "$TMP/pack.log" && say "✔" "ломкий файл пропущен" || { say "✘" "ломкий файл упакован — разбор сломается"; fail=1; }
grep -q "образец" "$TMP/pack.log" && { say "✘" "безобидные образцы считаются секретом — документы выпадут"; fail=1; } || say "✔" "образцы из инструкций передаются (не считаются секретом)"

python3 "$ROOT/tools/unpack_bundle.py" "$OUT" --dest "$DST" > "$TMP/unpack.log" 2>&1
ok=1
diff -r "$SRC/00-обычный.md" "$DST/пакет/00-обычный.md" >/dev/null 2>&1 || ok=0
diff -r "$SRC/инструкция-образец.md" "$DST/пакет/инструкция-образец.md" >/dev/null 2>&1 || ok=0
diff -r "$SRC/вложенная папка/ещё-образец.md" "$DST/пакет/вложенная папка/ещё-образец.md" >/dev/null 2>&1 || ok=0
[ "$ok" = "1" ] && say "✔" "разложилось побайтно (включая русские имена и вложенную папку)" || { say "✘" "содержимое после раскладки не совпадает"; fail=1; }

if [ "$fail" = "1" ]; then
  echo "Канал «пакет одним файлом» сломан — смотрите $TMP"
  exit 1
fi
echo "Канал «пакет одним файлом» работает: упаковка и раскладка проверены."
